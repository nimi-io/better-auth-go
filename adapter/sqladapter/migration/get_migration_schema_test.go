// Port of packages/better-auth/src/db/get-migration-schema.test.ts and
// get-migration-unsafe-change.test.ts. Each test gets a fresh database; the upstream
// "search_path" pools become connections with a search_path parameter.

func tableNamesIn(t *testing.T, tdb testDB, schema string) []string {
	t.Helper()
	rows, err := tdb.conn.Query(`SELECT table_name FROM information_schema.tables WHERE table_schema = $1 AND table_type = 'BASE TABLE'`, schema)
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	var out []string
	for rows.Next() {
		var n string
		if err := rows.Scan(&n); err != nil {
			t.Fatal(err)
		}
		out = append(out, n)
	}
	return out
}

func TestPostgresSchemaDetection(t *testing.T) {
	const customSchema = "auth_test"
	setup := func(t *testing.T) testDB {
		tdb := openDB(t, dialect.Postgres, customSchema)
		tdb.exec(t, `CREATE SCHEMA `+customSchema,
			`CREATE TABLE public.user (id SERIAL PRIMARY KEY, email VARCHAR(255) NOT NULL, name VARCHAR(255))`)
		return tdb
	}

	t.Run("should detect custom schema from search_path", func(t *testing.T) {
		p := mustPlan(t, setup(t), `{}`, Options{})
		created := findChange(p.ToBeCreated, "user")
		if created == nil || findChange(p.ToBeAdded, "user") != nil {
			t.Fatalf("user created=%v added=%v", created, findChange(p.ToBeAdded, "user"))
		}
		for _, f := range []string{"email", "name", "emailVerified"} {
			if !hasField(created, f) {
				t.Fatalf("missing %s", f)
			}
		}
	})

	t.Run("should detect custom schema with CamelCasePlugin enabled", func(t *testing.T) {
		t.Skip("TS-only: Kysely's CamelCasePlugin has no Go equivalent (column names are configured through fields)")
	})

	t.Run("should not be affected by tables in public schema when using custom schema", func(t *testing.T) {
		tdb := setup(t)
		p := mustPlan(t, tdb, `{}`, Options{})
		if findChange(p.ToBeCreated, "user") == nil {
			t.Fatal("user not created")
		}
		if names := tableNamesIn(t, tdb, "public"); !contains(names, "user") {
			t.Fatalf("public tables = %v", names)
		}
	})

	t.Run("should only inspect tables in public schema when using default connection", func(t *testing.T) {
		tdb := openDB(t, dialect.Postgres, "")
		tdb.exec(t, `CREATE TABLE public.user (id TEXT PRIMARY KEY NOT NULL, email TEXT NOT NULL, name TEXT NOT NULL, "emailVerified" BOOLEAN NOT NULL, image TEXT, "createdAt" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL, "updatedAt" TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL)`)
		p := mustPlan(t, tdb, `{}`, Options{})
		if findChange(p.ToBeCreated, "user") != nil || findChange(p.ToBeAdded, "user") != nil {
			t.Fatal("user planned")
		}
		if findChange(p.ToBeCreated, "session") == nil {
			t.Fatal("session not created")
		}
	})

	t.Run("should create tables in custom schema when running migrations", func(t *testing.T) {
		tdb := setup(t)
		run(t, mustPlan(t, tdb, `{}`, Options{}))
		names := tableNamesIn(t, tdb, customSchema)
		for _, n := range []string{"user", "session", "account", "verification"} {
			if !contains(names, n) {
				t.Fatalf("%s missing from %v", n, names)
			}
		}
	})

	t.Run("should use uuid for id when generateId is uuid", func(t *testing.T) {
		tdb := openDB(t, dialect.Postgres, "uuid_test")
		tdb.exec(t, `CREATE SCHEMA uuid_test`)
		cfg := `{"advanced": {"database": {"generateId": "uuid"}}}`
		run(t, mustPlan(t, tdb, cfg, Options{}))
		// Stands in for auth.api.signUpEmail: the database generates the id.
		id := queryString(t, tdb, `INSERT INTO "user" ("name", "email", "emailVerified") VALUES ('test user', 'test@test.com', false) RETURNING "id"`)
		if !regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`).MatchString(id) {
			t.Fatalf("id = %s", id)
		}
		if got := compiled(mustPlan(t, tdb, cfg, Options{})); got != ";" {
			t.Fatalf("second round = %q", got)
		}
	})

	t.Run("should use GENERATED BY DEFAULT AS IDENTITY instead of SERIAL for serial ids", func(t *testing.T) {
		tdb := openDB(t, dialect.Postgres, "identity_test")
		tdb.exec(t, `CREATE SCHEMA identity_test`)
		sql := compiled(mustPlan(t, tdb, `{"advanced": {"database": {"generateId": "serial"}}}`, Options{}))
		if !strings.Contains(sql, "GENERATED BY DEFAULT AS IDENTITY") || strings.Contains(sql, "SERIAL") {
			t.Fatalf("unexpected plan:\n%s", sql)
		}
		if !regexp.MustCompile(`(?is)create table.*?"user".*?\(`).MatchString(sql) {
			t.Fatal("no user table")
		}
		if len(regexp.MustCompile(`(?i)"id"\s+integer\s+GENERATED\s+BY\s+DEFAULT\s+AS\s+IDENTITY`).FindAllString(sql, -1)) == 0 {
			t.Fatal("no identity id column")
		}
	})
}

func TestPostgresColumnAdditions(t *testing.T) {
	setup := func(t *testing.T) testDB {
		tdb := openDB(t, dialect.Postgres, "column_test")
		tdb.exec(t, `CREATE SCHEMA column_test`)
		run(t, mustPlan(t, tdb, `{}`, Options{}))
		return tdb
	}

	t.Run("should update default tables with plugin schema fields", func(t *testing.T) {
		p := mustPlan(t, setup(t), `{"plugins": [{"id": "test", "schema": {
			"user": {"fields": {"role": {"type": "string"}}},
			"session": {"fields": {"impersonatedBy": {"type": "string"}}}}}]}`, Options{})
		if len(p.ToBeCreated) != 0 || len(p.ToBeAdded) != 2 {
			t.Fatalf("created %d added %d", len(p.ToBeCreated), len(p.ToBeAdded))
		}
		if !hasField(findChange(p.ToBeAdded, "user"), "role") || !hasField(findChange(p.ToBeAdded, "session"), "impersonatedBy") {
			t.Fatalf("toBeAdded = %v", names(p.ToBeAdded))
		}
	})

	t.Run("should generate valid PostgreSQL CREATE INDEX syntax for indexed columns added to existing tables", func(t *testing.T) {
		sql := lowerSQL(mustPlan(t, setup(t), externalIDPlugin, Options{}))
		if !strings.Contains(sql, "create index") || strings.Contains(sql, "add index") {
			t.Fatalf("unexpected plan:\n%s", sql)
		}
	})
}

const externalIDPlugin = `{"plugins": [{"id": "test-index", "schema": {"user": {"fields": {
	"externalId": {"type": "string", "index": true, "required": false}}}}}]}`

func TestIndexGenerationForColumnsAddedToExistingTables(t *testing.T) {
	migrated := func(t *testing.T) testDB {
		tdb := sqliteDB(t)
		run(t, mustPlan(t, tdb, `{}`, Options{}))
		return tdb
	}

	t.Run("should use CREATE INDEX when adding indexed columns to existing SQLite tables", func(t *testing.T) {
		sql := lowerSQL(mustPlan(t, migrated(t), externalIDPlugin, Options{}))
		if !strings.Contains(sql, "create index") || strings.Contains(sql, "add index") {
			t.Fatalf("unexpected plan:\n%s", sql)
		}
	})

	t.Run("should enforce unique indexed fields on new tables without a duplicate index", func(t *testing.T) {
		tdb := sqliteDB(t)
		p := mustPlan(t, tdb, `{"plugins": [{"id": "test-unique-index", "schema": {"uniqueTable": {"fields": {
			"slug": {"type": "string", "index": true, "unique": true, "required": true}}}}}]}`, Options{})
		sql := lowerSQL(p)
		if !regexp.MustCompile(`(?s)create table "uniquetable"[^;]*"slug" text not null unique`).MatchString(sql) {
			t.Fatalf("no inline unique:\n%s", sql)
		}
		if strings.Contains(sql, "uniquetable_slug_uidx") {
			t.Fatal("duplicate unique index")
		}
		run(t, p)
		tdb.exec(t, `INSERT INTO "uniqueTable" ("id", "slug") VALUES ('first', 'shared')`)
		if _, err := tdb.conn.Exec(`INSERT INTO "uniqueTable" ("id", "slug") VALUES ('second', 'shared')`); err == nil {
			t.Fatal("duplicate slug accepted")
		}
	})

	t.Run("should execute runMigrations without error when adding indexed columns to existing tables", func(t *testing.T) {
		run(t, mustPlan(t, migrated(t), externalIDPlugin, Options{}))
	})

	t.Run("should execute runMigrations when adding a new table with indexed columns to an existing database", func(t *testing.T) {
		run(t, mustPlan(t, migrated(t), `{"plugins": [{"id": "test-new-table", "schema": {"apikey": {"fields": {
			"configId": {"type": "string", "required": true, "index": true},
			"referenceId": {"type": "string", "required": true, "index": true},
			"key": {"type": "string", "required": true, "index": true},
			"createdAt": {"type": "date", "required": true},
			"updatedAt": {"type": "date", "required": true}}}}}]}`, Options{}))
	})

	t.Run("should execute runMigrations when upgrading an existing table with new indexed columns", func(t *testing.T) {
		tdb := sqliteDB(t)
		run(t, mustPlan(t, tdb, `{"plugins": [{"id": "old-apikey", "schema": {"apikey": {"fields": {
			"key": {"type": "string", "required": true},
			"userId": {"type": "string", "required": true},
			"createdAt": {"type": "date", "required": true},
			"updatedAt": {"type": "date", "required": true}}}}}]}`, Options{}))
		p := mustPlan(t, tdb, `{"plugins": [{"id": "new-apikey", "schema": {"apikey": {"fields": {
			"configId": {"type": "string", "required": true, "index": true},
			"referenceId": {"type": "string", "required": true, "index": true},
			"key": {"type": "string", "required": true, "index": true},
			"userId": {"type": "string", "required": true},
			"createdAt": {"type": "date", "required": true},
			"updatedAt": {"type": "date", "required": true}}}}}]}`, Options{})
		added := findChange(p.ToBeAdded, "apikey")
		if !hasField(added, "configId") || !hasField(added, "referenceId") {
			t.Fatalf("toBeAdded = %v", names(p.ToBeAdded))
		}
		run(t, p)
	})

	t.Run("should not detect migration changes for SQLite bigint fields on subsequent runs", func(t *testing.T) {
		tdb := sqliteDB(t)
		cfg := `{"rateLimit": {"storage": "database"}}`
		run(t, mustPlan(t, tdb, cfg, Options{}))
		p := mustPlan(t, tdb, cfg, Options{})
		if len(p.ToBeCreated) != 0 || len(p.ToBeAdded) != 0 || compiled(p) != ";" {
			t.Fatalf("second run:\n%s", compiled(p))
		}
	})

	t.Run("should add table indexes to existing device authorization columns", func(t *testing.T) {
		tdb := sqliteDB(t)
		run(t, mustPlan(t, tdb, `{"plugins": [{"id": "old-device-code", "schema": {"deviceCode": {"fields": {
			"deviceCode": {"type": "string", "required": true},
			"userCode": {"type": "string", "required": true}}}}}]}`, Options{}))
		upgraded := `{"plugins": [{"id": "new-device-code", "schema": {"deviceCode": {
			"fields": {
				"deviceCode": {"type": "string", "required": true},
				"userCode": {"type": "string", "required": true}},
			"indexes": [{"fields": ["deviceCode"], "unique": true}, {"fields": ["userCode"], "unique": true}]}}}]}`
		p := mustPlan(t, tdb, upgraded, Options{})
		sql := compiled(p)
		if len(p.ToBeAdded) != 0 || !strings.Contains(sql, `create unique index "deviceCode_deviceCode_uidx"`) || !strings.Contains(sql, `create unique index "deviceCode_userCode_uidx"`) {
			t.Fatalf("unexpected plan:\n%s", sql)
		}
		if p.Empty() {
			t.Fatal("a plan with only indexes must not be empty")
		}
		run(t, p)
		if got := compiled(mustPlan(t, tdb, upgraded, Options{})); got != ";" {
			t.Fatalf("repeated = %q", got)
		}
	})
}

func TestPostgresConfiguredSchemaName(t *testing.T) {
	const schema = "schema_name_test"
	t.Run("creates the schema and its tables, and leaves the public schema alone", func(t *testing.T) {
		tdb := openDB(t, dialect.Postgres, "")
		before := tableNamesIn(t, tdb, "public")
		p := mustPlan(t, tdb, `{}`, Options{SchemaName: schema})
		sql := compiled(p)
		if !strings.Contains(sql, `create schema if not exists "`+schema+`"`) || !strings.Contains(sql, `create table "`+schema+`"."user"`) {
			t.Fatalf("unexpected plan:\n%s", sql)
		}
		run(t, p)
		names := tableNamesIn(t, tdb, schema)
		for _, n := range []string{"user", "session", "account", "verification"} {
			if !contains(names, n) {
				t.Fatalf("%s missing from %v", n, names)
			}
		}
		if after := tableNamesIn(t, tdb, "public"); len(after) != len(before) {
			t.Fatalf("public tables changed: %v -> %v", before, after)
		}
	})

	t.Run("reads and writes through the configured schema at runtime", func(t *testing.T) {
		t.Skip("runtime reads and writes belong to the SQL adapter (adapter/sqladapter), not the planner")
	})

	t.Run("plans no further changes once the schema is migrated", func(t *testing.T) {
		tdb := openDB(t, dialect.Postgres, "")
		run(t, mustPlan(t, tdb, `{}`, Options{SchemaName: schema}))
		if got := compiled(mustPlan(t, tdb, `{}`, Options{SchemaName: schema})); got != ";" {
			t.Fatalf("second plan = %q", got)
		}
	})
}

const unsafeChangeConfig = `{"plugins": [{"id": "unsafe-change", "schema": {"populatedNoDefault": {"fields": {
	"name": {"type": "string"},
	"connectionIssuer": {"type": "string", "required": true}}}}}]}`

func TestUnsafeMigrationGuardrail(t *testing.T) {
	check := func(t *testing.T, tdb testDB, columnsQuery string, args ...any) {
		t.Helper()
		_, err := planJSON(t, tdb, unsafeChangeConfig, Options{})
		var unsafe *UnsafeMigrationError
		if !errors.As(err, &unsafe) {
			t.Fatalf("expected *UnsafeMigrationError, got %v", err)
		}
		rows, err := tdb.conn.Query(columnsQuery, args...)
		if err != nil {
			t.Fatal(err)
		}
		defer rows.Close()
		for rows.Next() {
			var c string
			if err := rows.Scan(&c); err != nil {
				t.Fatal(err)
			}
			if c == "connectionIssuer" {
				t.Fatal("connectionIssuer was added")
			}
		}
	}

	t.Run("PostgreSQL refuses a required no-default column on a populated table before any statement executes", func(t *testing.T) {
		const schema = "unsafe_change_test"
		tdb := openDB(t, dialect.Postgres, schema)
		tdb.exec(t, `CREATE SCHEMA `+schema,
			`CREATE TABLE "populatedNoDefault" ("id" text primary key not null, "name" text not null)`,
			`INSERT INTO "populatedNoDefault" ("id", "name") VALUES ('p1', 'existing-row')`)
		check(t, tdb, `SELECT column_name FROM information_schema.columns WHERE table_schema = $1 AND table_name = 'populatedNoDefault'`, schema)
	})

	t.Run("MySQL refuses a required no-default column on a populated table before any statement executes", func(t *testing.T) {
		tdb := openDB(t, dialect.MySQL, "")
		tdb.exec(t, "CREATE TABLE `populatedNoDefault` (`id` varchar(36) primary key not null, `name` text not null)",
			"INSERT INTO `populatedNoDefault` (`id`, `name`) VALUES ('p1', 'existing-row')")
		check(t, tdb, "SELECT COLUMN_NAME FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = 'populatedNoDefault'")
	})
}
