func user(name string) adapter.Record {
	return adapter.Record{"name": name, "email": strings.ToLower(name) + "@example.com"}
}

func names(rs []adapter.Record) []string {
	out := make([]string, len(rs))
	for i, r := range rs {
		out[i] = fmt.Sprint(r["name"])
	}
	return out
}

func sortedNames(rs []adapter.Record) string {
	n := names(rs)
	for i := 1; i < len(n); i++ {
		for j := i; j > 0 && n[j] < n[j-1]; j-- {
			n[j], n[j-1] = n[j-1], n[j]
		}
	}
	return strings.Join(n, ",")
}

