// ---- adapter construction ----

type setup struct {
	cfg    Config
	opts   adapter.Options
	schema dbschema.Options
	ddl    ddlOptions
	// noTables skips table creation.
	noTables bool
}

// newAdapter creates the tables of the setup and returns the adapter plus its logger.
func (e *env) newAdapter(t *testing.T, s setup) (adapter.Adapter, *captureLogger) {
	t.Helper()
	schema := s.opts.Schema
	if schema == nil {
		schema = testSchema(s.schema)
	}
	s.ddl.idMode = s.opts.IDMode
	s.ddl.usePlural = s.cfg.UsePlural
	if s.ddl.schemaName == "" {
		s.ddl.schemaName = s.cfg.SchemaName
	}
	if !s.noTables {
		e.createTables(t, schema, s.ddl)
	}
	log := &captureLogger{}
	opts := s.opts
	opts.Schema = schema
	if opts.Logger == nil {
		opts.Logger = log
	}
	s.cfg.DebugLogs = true
	if e.adapterDialect != "" && s.cfg.Dialect == "" {
		s.cfg.Dialect = e.adapterDialect
	}
	a, err := New(e.db, s.cfg)(opts)
	if err != nil {
		t.Fatal(err)
	}
	return a, log
}

func customOf(a adapter.Adapter) adapter.CustomAdapter {
	return a.(interface{ Custom() adapter.CustomAdapter }).Custom()
}

// captureLogger records debug statements and warnings.
type captureLogger struct {
	mu    sync.Mutex
	stmts []string
	warns []string
}

func (c *captureLogger) Info(msg string, _ ...any) {
	c.mu.Lock()
	defer c.mu.Unlock()
	for _, p := range []string{"[Kysely Adapter] query: ", "[Kysely Adapter] exec: "} {
		if strings.HasPrefix(msg, p) {
			c.stmts = append(c.stmts, strings.TrimPrefix(msg, p))
		}
	}
}
func (c *captureLogger) Debug(string, ...any) {}
func (c *captureLogger) Warn(msg string, args ...any) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.warns = append(c.warns, fmt.Sprint(append([]any{msg}, args...)...))
}
func (c *captureLogger) Error(msg string, args ...any) { c.Warn(msg, args...) }

func (c *captureLogger) reset() {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.stmts = nil
}

func (c *captureLogger) statements() []string {
	c.mu.Lock()
	defer c.mu.Unlock()
	return append([]string(nil), c.stmts...)
}

func (c *captureLogger) warnings() []string {
	c.mu.Lock()
	defer c.mu.Unlock()
	return append([]string(nil), c.warns...)
}

