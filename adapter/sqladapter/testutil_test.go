var allDialects = []Dialect{Postgres, MySQL, SQLite}

// env is one test database.
type env struct {
	d  Dialect
	db *sql.DB
	// adapterDialect, when set, configures the adapter with a dialect other than the
	// database's (upstream runs the MySQL code path against SQLite this way).
	adapterDialect Dialect
}

func openDB(t *testing.T, d Dialect) *sql.DB {
	t.Helper()
	switch d {
	case Postgres:
		return testdb.Postgres(t)
	case MySQL:
		return testdb.MySQL(t)
	default:
		return testdb.SQLite(t)
	}
}

// forEachDialect runs fn against a fresh database of every dialect.
func forEachDialect(t *testing.T, fn func(t *testing.T, e *env)) {
	t.Helper()
	for _, d := range allDialects {
		t.Run(string(d), func(t *testing.T) {
			t.Parallel()
			fn(t, &env{d: d, db: openDB(t, d)})
		})
	}
}

// forEachDialectAndMySQLOnSQLite is forEachDialect plus the MySQL code path executed
// against SQLite, exactly as upstream's with-returning-mysql.test.ts does.
func forEachDialectAndMySQLOnSQLite(t *testing.T, fn func(t *testing.T, e *env)) {
	t.Helper()
	forEachDialect(t, fn)
	t.Run("mysql-branch-on-sqlite", func(t *testing.T) {
		t.Parallel()
		fn(t, &env{d: SQLite, db: openDB(t, SQLite), adapterDialect: MySQL})
	})
}

// sql rewrites a statement written with "double quotes" and ? placeholders for the dialect.
func (e *env) sql(s string) string {
	if e.d == MySQL {
		s = strings.ReplaceAll(s, `"`, "`")
	}
	if e.d == Postgres {
		var b strings.Builder
		n := 0
		for _, r := range s {
			if r == '?' {
				n++
				b.WriteString("$" + strconv.Itoa(n))
				continue
			}
			b.WriteRune(r)
		}
		s = b.String()
	}
	return s
}

func (e *env) exec(t *testing.T, s string, args ...any) {
	t.Helper()
	if _, err := e.db.Exec(e.sql(s), args...); err != nil {
		t.Fatalf("exec %s: %v", e.sql(s), err)
	}
}

func (e *env) rows(t *testing.T, s string, args ...any) []adapter.Record {
	t.Helper()
	rows, err := e.db.Query(e.sql(s), args...)
	if err != nil {
		t.Fatalf("query %s: %v", e.sql(s), err)
	}
	recs, err := scanRows(rows)
	if err != nil {
		t.Fatal(err)
	}
	return recs
}

func (e *env) row(t *testing.T, s string, args ...any) adapter.Record {
	t.Helper()
	rs := e.rows(t, s, args...)
	if len(rs) != 1 {
		t.Fatalf("%s: expected 1 row, got %d", s, len(rs))
	}
	return rs[0]
}

// ---- DDL mirroring getMigrations (packages/better-auth/src/db/get-migration.ts) ----

type ddlOptions struct {
	idMode     adapter.IDMode
	usePlural  bool
	schemaName string // PostgreSQL schema
	// idDefault overrides the id column default (generateId: false tests).
	idDefault string
}

// columnType is getType() of get-migration.ts.
func columnType(d Dialect, f dbschema.Field, idMode adapter.IDMode) string {
	serial, uuid := idMode == adapter.IDSerial, idMode == adapter.IDUUID
	if f.References != nil && f.References.Field == "id" {
		switch d {
		case Postgres:
			if serial {
				return "integer"
			}
			if uuid {
				return "uuid"
			}
			return "text"
		case MySQL:
			if serial {
				return "integer"
			}
			return "varchar(36)"
		default:
			if serial {
				return "integer"
			}
			return "text"
		}
	}
	switch f.Type {
	case dbschema.TypeString:
		switch d {
		case MySQL:
			switch {
			case f.Unique:
				return "varchar(255)"
			case f.References != nil:
				return "varchar(36)"
			case f.Sortable, f.Index:
				return "varchar(255)"
			}
			return "text"
		default:
			return "text"
		}
	case dbschema.TypeEnum:
		return "text"
	case dbschema.TypeBoolean:
		if d == SQLite {
			return "integer"
		}
		return "boolean"
	case dbschema.TypeNumber:
		if f.BigInt {
			return "bigint"
		}
		return "integer"
	case dbschema.TypeDate:
		switch d {
		case Postgres:
			return "timestamptz"
		case MySQL:
			return "timestamp(3)"
		}
		return "date"
	case dbschema.TypeJSON, dbschema.TypeStringArray, dbschema.TypeNumberArray:
		switch d {
		case Postgres:
			return "jsonb"
		case MySQL:
			return "json"
		}
		return "text"
	}
	panic("unsupported type " + string(f.Type))
}

func idColumn(d Dialect, o ddlOptions) string {
	q := d.Quote("id")
	switch o.idMode {
	case adapter.IDSerial:
		switch d {
		case Postgres:
			return q + " integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL"
		case MySQL:
			return q + " integer AUTO_INCREMENT PRIMARY KEY NOT NULL"
		}
		return q + " integer PRIMARY KEY NOT NULL"
	case adapter.IDUUID:
		if d == Postgres {
			return q + " uuid PRIMARY KEY DEFAULT pg_catalog.gen_random_uuid() NOT NULL"
		}
	}
	typ := "text"
	if d == MySQL {
		typ = "varchar(36)"
	}
	if o.idDefault != "" {
		return q + " " + typ + " PRIMARY KEY DEFAULT " + o.idDefault + " NOT NULL"
	}
	return q + " " + typ + " PRIMARY KEY NOT NULL"
}

func physicalName(t *dbschema.Table, plural bool) string {
	if plural {
		return t.ModelName + "s"
	}
	return t.ModelName
}

// createTables creates every table of schema.
func (e *env) createTables(t *testing.T, schema *dbschema.Schema, o ddlOptions) {
	t.Helper()
	d := e.d
	if o.schemaName != "" {
		e.exec(t, "CREATE SCHEMA IF NOT EXISTS "+d.Quote(o.schemaName))
	}
	for _, tbl := range schema.Tables {
		cols := []string{idColumn(d, o)}
		for _, f := range tbl.Fields {
			c := d.Quote(f.Column()) + " " + columnType(d, f, o.idMode)
			if f.NotNull() {
				c += " NOT NULL"
			}
			if f.References != nil {
				ref := schema.Table(f.References.Model)
				onDelete := f.References.OnDelete
				if onDelete == "" {
					onDelete = "cascade"
				}
				col := f.References.Field
				if col != "id" {
					rf, _ := ref.Field(col)
					col = rf.Column()
				}
				target := d.QuoteTable(o.schemaName, physicalName(ref, o.usePlural))
				if d == SQLite { // SQLite foreign keys name a table of the same schema
					name := physicalName(ref, o.usePlural)
					target = d.Quote(name[strings.IndexByte(name, '.')+1:])
				}
				c += " REFERENCES " + target + " (" + d.Quote(col) + ") ON DELETE " + onDelete
			}
			if f.Unique {
				c += " UNIQUE"
			}
			if f.Type == dbschema.TypeDate && f.DefaultFunc != nil {
				switch d {
				case MySQL:
					c += " DEFAULT CURRENT_TIMESTAMP(3)"
				case Postgres:
					c += " DEFAULT CURRENT_TIMESTAMP"
				}
			}
			cols = append(cols, c)
		}
		stmt := "CREATE TABLE " + d.QuoteTable(o.schemaName, physicalName(tbl, o.usePlural)) + " (" + strings.Join(cols, ", ") + ")"
		if _, err := e.db.Exec(stmt); err != nil {
			t.Fatalf("%s: %v", stmt, err)
		}
	}
}

