package sqladapter

// Port of packages/kysely-adapter/src/sqlite-dialect-mutations.test.ts. Upstream checks
// that its custom node:sqlite / bun:sqlite Kysely dialects surface mutation metadata and
// RETURNING rows; the Go adapter relies on the same contract from each database/sql driver
// (RowsAffected for updateMany/deleteMany, LastInsertId for MySQL serial ids, RETURNING rows
// for PostgreSQL and SQLite), so the cases run against every driver.

import (
	"testing"
)

func createUsersTable(t *testing.T, e *env) {
	t.Helper()
	switch e.d {
	case Postgres:
		e.exec(t, `CREATE TABLE "users" ("id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "name" TEXT, "value" TEXT)`)
	case MySQL:
		e.exec(t, `CREATE TABLE "users" ("id" integer AUTO_INCREMENT PRIMARY KEY, "name" TEXT, "value" TEXT)`)
	default:
		e.exec(t, `CREATE TABLE "users" ("id" INTEGER PRIMARY KEY AUTOINCREMENT, "name" TEXT, "value" TEXT)`)
	}
}

func TestDriverMutationMetadata(t *testing.T) {
	t.Run("binds multiple parameters and surfaces insert/update/delete metadata", func(t *testing.T) {
		forEachDialect(t, func(t *testing.T, e *env) {
			createUsersTable(t, e)
			res, err := e.db.Exec(e.sql(`INSERT INTO "users" ("name", "value") VALUES (?, ?)`), "alice", "first")
			if err != nil {
				t.Fatal(err)
			}
			if n, err := res.RowsAffected(); err != nil || n != 1 {
				t.Fatalf("inserted rows %d %v", n, err)
			}
			if e.d != Postgres { // PostgreSQL has no insert id; RETURNING is used instead
				if id, err := res.LastInsertId(); err != nil || id != 1 {
					t.Fatalf("insert id %d %v", id, err)
				}
			}
			found := e.rows(t, `SELECT * FROM "users" WHERE "name" = ? AND "value" = ?`, "alice", "first")
			if len(found) != 1 || found[0]["name"] != "alice" {
				t.Fatalf("found %v", found)
			}
			res, err = e.db.Exec(e.sql(`UPDATE "users" SET "value" = ? WHERE "name" = ?`), "second", "alice")
			if err != nil {
				t.Fatal(err)
			}
			if n, _ := res.RowsAffected(); n != 1 {
				t.Fatalf("updated rows %d", n)
			}
			res, err = e.db.Exec(e.sql(`DELETE FROM "users" WHERE "name" = ?`), "alice")
			if err != nil {
				t.Fatal(err)
			}
			if n, _ := res.RowsAffected(); n != 1 {
				t.Fatalf("deleted rows %d", n)
			}
		})
	})

	t.Run("keeps row results for RETURNING mutations", func(t *testing.T) {
		forEachDialect(t, func(t *testing.T, e *env) {
			if !e.d.SupportsReturning() {
				t.Skip("MySQL has no RETURNING; the adapter re-selects inserted rows instead")
			}
			createUsersTable(t, e)
			inserted := e.row(t, `INSERT INTO "users" ("name", "value") VALUES (?, ?) RETURNING *`, "bob", "x")
			if inserted["name"] != "bob" || inserted["id"] != int64(1) {
				t.Fatalf("returned %v", inserted)
			}
		})
	})
}
